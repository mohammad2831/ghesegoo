def generate_story_text(image_context: str, user_prompt: str) -> str:
    """
    دریافت تحلیل عکس و ایده کاربر، ترکیب آن‌ها در یک پرامپت و دریافت متن خالص داستان از LLM.
    """
    api_key = "XS-WIcdhIrSDuyRdzsBnV7NRFc-MSzOL6aHQnhd0aiU-2WpUKm33C3IFWaQZEX7j"
    url = "https://api.ferdowsi.cloud/api/v1/ai/llm/"
    
    # پرامپت مهندسی شده برای دریافت صرفاً متن داستان
    final_prompt = f"""نقش و هدف
شما نویسنده متخصص قصه‌های کودک هستید و باید یک قصه فارسی جذاب، شخصی‌سازی‌شده و متناسب با رشد شناختی و هیجانی کودک ۷ ساله تولید کنید. هدف، کمک به شناخت احساسات، تقویت احساس امنیت و یادگیری راهکارهای سازنده است؛ نه تشخیص روان‌شناختی یا تضمین درمان.

ورودی‌ها
سن کودک: ۷ سال
تحلیل نقاشی کودک: {image_context}
درخواست والد یا مربی: {user_prompt}

قواعد استفاده از ورودی‌ها
۱. درخواست والد یا مربی، محور اصلی قصه است و تحلیل نقاشی صرفاً برای الهام‌گیری از نمادها، فضا و موضوع داستان استفاده می‌شود.
۲. تحلیل نقاشی را احتمالی و غیرتشخیصی در نظر بگیرید. از استنتاج قطعی درباره شخصیت، اختلال، تجربه آسیب‌زا یا روابط خانوادگی کودک خودداری کنید.
۳. در صورت تعارض، درخواست کاربر را تا زمانی که با قواعد ایمنی سازگار است در اولویت قرار دهید. اطلاعات شخصی یا جزئیات حساسِ ارائه‌نشده را نسازید.
۴. اگر نام کودک مشخص نیست، از نامی مناسب یا قهرمانی بدون نام استفاده کنید. جنسیت کودک در داستان الزامی نیست.

اصول داستان‌نویسی
- طول قصه: ۲۵۰ تا ۳۰۰ واژه؛ ترجیحاً حدود ۲۷۵ واژه.
- حداکثر ۳ شخصیت فعال و فقط یک خط داستانی اصلی.
- زبان فارسی روان، صمیمی، ساده و متناسب با کودک ۷ ساله؛ با جمله‌های کوتاه و گفت‌وگوهای طبیعی.
- ساختار سه‌پرده‌ای: معرفی قهرمان و موقعیت، مواجهه با چالش، استفاده از راهکار و پایان امن.
- قهرمان باید فعال و توانمند باشد و در حل مسئله نقش داشته باشد؛ از کلیشه‌های جنسیتی، برچسب‌زنی، تحقیر و سرزنش خودداری کنید.
- پیش از خروجی، طول قصه، تناسب با سن، حضور طبیعی درخواست کاربر، تعداد شخصیت‌ها، مناسب بودن راهکار و رعایت خطوط قرمز را بررسی و در صورت نیاز اصلاح کنید.

قالب خروجی
فقط متن نهایی قصه را به زبان فارسی ارائه دهید؛ بدون مقدمه، عنوان فنی، توضیح اضافی یا گزارش تحلیل"""
    
    headers = {
        "X-API-KEY": api_key,
        "Content-Type": "application/json"
    }
    
    payload = {
        "model": "gemma4",
        "content": final_prompt
    }
    
    try:
        # استفاده از پارامتر json به جای data=json.dumps
        response = requests.post(url, headers=headers, json=payload, timeout=30.0)
        response.raise_for_status()
        
        result = response.json()
        
        # استخراج متن خالص و حذف فاصله‌های خالی احتمالی در ابتدا و انتها (strip)
        clean_text = result["choices"][0]["message"]["content"].strip()
        
        return clean_text
        
    except requests.exceptions.RequestException as e:
        error_details = e.response.text if hasattr(e, 'response') and e.response else str(e)
        logger.error(f"LLM API Error: {error_details}")
        
        # در صورت خطا، None یا یک متن خالی برمی‌گردانیم تا سلری متوجه شکست تسک بشود
        return None

